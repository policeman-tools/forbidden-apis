package de.thetaphi.forbiddenapis.maven;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.Collections;
import java.util.List;
import java.util.Locale;
import java.util.Set;

import org.apache.maven.doxia.sink.Sink;
import org.apache.maven.plugin.MojoExecutionException;
import org.apache.maven.plugins.annotations.Parameter;
import org.apache.maven.reporting.MavenReport;
import org.apache.maven.reporting.MavenReportException;

import de.thetaphi.forbiddenapis.AsmUtils;
import de.thetaphi.forbiddenapis.Checker;
import de.thetaphi.forbiddenapis.CheckerResult;
import de.thetaphi.forbiddenapis.ForbiddenApiException;
import de.thetaphi.forbiddenapis.ViolationSeverity;

/**
 * Base class for forbiddenapis report Mojos. They run the same checks as the corresponding check Mojos,
 * but instead of failing the build, they list all violations in a report for the Maven site.
 * <p>
 * This class implements the {@link MavenReport} interface directly (without {@code maven-reporting-impl}),
 * so the plugin works with all versions of {@code maven-site-plugin} (which provides the reporting and
 * Doxia APIs at runtime), regardless of the Doxia version they use.
 * @since 3.12
 */
public abstract class AbstractReportMojo extends AbstractCheckMojo implements MavenReport {

  /**
   * Directory where the report is written to, if the goal is executed directly (and not as part of the
   * Maven site). If the report is generated by {@code maven-site-plugin}, it decides about the location.
   * @since 3.12
   */
  @Parameter(defaultValue = "${project.reporting.outputDirectory}", readonly = true, required = true)
  private File outputDirectory;

  /** The output directory as set by {@code maven-site-plugin}, see {@link #setReportOutputDirectory(File)}. */
  private File reportOutputDirectory;

  /** Returns a human readable description of the checked classes (e.g., "main classes"), used in the report. */
  abstract String getScopeDescription();

  /**
   * Returns the relative output path of the report (without extension). This method was added in
   * the reporting API 4.0.0 as replacement for {@link #getOutputName()}, so it has no {@code @Override} annotation.
   */
  public String getOutputPath() {
    return getOutputName();
  }

  @Override
  public String getCategoryName() {
    return CATEGORY_PROJECT_REPORTS;
  }

  @Override
  public boolean isExternalReport() {
    return false;
  }

  @Override
  public boolean canGenerateReport() {
    return hasClassesToCheck();
  }

  @Override
  public void setReportOutputDirectory(File reportOutputDirectory) {
    this.reportOutputDirectory = reportOutputDirectory;
  }

  @Override
  public File getReportOutputDirectory() {
    return (reportOutputDirectory != null) ? reportOutputDirectory : outputDirectory;
  }

  /**
   * Generates the report. This method is called by {@code maven-site-plugin} versions using the reporting
   * API 3.0 or 3.1.1 (Doxia 1.x), e.g., versions 3.3 to 3.10.0 and 3.12.x. It delegates to {@link #generate(Sink, Locale)}.
   */
  @Override
  @SuppressWarnings("deprecation")
  public void generate(org.codehaus.doxia.sink.Sink sink, Locale locale) throws MavenReportException {
    final Sink doxiaSink = sink; // this selects the overload below (prevents endless recursion)
    generate(doxiaSink, locale);
  }

  /**
   * Generates the report. This method is called by {@code maven-site-plugin} version 3.11.0 (reporting API 3.1.0)
   * and all versions since 3.20.0 (reporting API 4.x, Doxia 2.x). It is not part of the older reporting API
   * we compile against, so it has no {@code @Override} annotation.
   */
  public void generate(Sink sink, Locale locale) throws MavenReportException {
    ReportRenderer renderer;
    try {
      renderer = createReportRenderer();
    } catch (MojoExecutionException mee) {
      throw new MavenReportException(mee.getMessage(), mee);
    }
    if (renderer == null) {
      // the check was skipped, the reason was already logged:
      renderer = new ReportRenderer(getName(Locale.ENGLISH), getScopeDescription(), null, Collections.<String>emptySet());
    }
    renderer.render(sink);
  }

  /**
   * Generates the report as standalone HTML page, if the goal is executed directly
   * (and not as part of the Maven site).
   */
  @Override
  public void execute() throws MojoExecutionException {
    final ReportRenderer renderer = createReportRenderer();
    if (renderer == null) {
      // the check was skipped, the reason was already logged
      return;
    }
    final StringBuilder html = new StringBuilder();
    renderer.render(StandaloneHtmlSink.create(html));
    final File reportDirectory = getReportOutputDirectory();
    final File reportFile = new File(reportDirectory, getOutputName() + ".html");
    try {
      Files.createDirectories(reportDirectory.toPath());
      Files.write(reportFile.toPath(), html.toString().getBytes(StandardCharsets.UTF_8));
    } catch (IOException ioe) {
      throw new MojoExecutionException("Failed to write forbiddenapis report: " + reportFile, ioe);
    }
    getLog().info("Forbidden API report written to: " + reportFile);
  }

  /** Runs the check and returns a renderer for the results; returns {@code null}, if the check was skipped. */
  private ReportRenderer createReportRenderer() throws MojoExecutionException {
    return executeChecker(new CheckerAction<ReportRenderer>() {
      @Override
      public ReportRenderer run(Checker checker) throws ForbiddenApiException {
        getLog().info("Scanning classes for violations to report...");
        final List<CheckerResult> results = checker.runWithResults();
        final Set<String> missingClasses = checker.getMissingClasses();
        if (!missingClasses.isEmpty()) {
          getLog().warn("While scanning classes to check, the following referenced classes were not found on classpath (this may miss some violations):");
          getLog().warn(AsmUtils.formatClassesAbbreviated(missingClasses));
        }
        final ReportRenderer renderer = new ReportRenderer(getName(Locale.ENGLISH), getScopeDescription(), results, missingClasses);
        getLog().info(String.format(Locale.ENGLISH,
            "Scanned %d class file(s) for forbidden API invocations, %d violation(s) reported (%d error(s), %d warning(s)).",
            results.size(), renderer.getViolationCount(),
            renderer.getViolationCount(ViolationSeverity.ERROR), renderer.getViolationCount(ViolationSeverity.WARNING)));
        return renderer;
      }
    });
  }

}
